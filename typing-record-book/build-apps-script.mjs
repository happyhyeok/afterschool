import { readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const splitDirectory = join(root, "apps-script-split");
const outputPath = join(root, "apps-script", "Code.gs");
const files = (await readdir(splitDirectory))
  .filter((name) => /^\d{2}_.+\.gs$/.test(name))
  .sort();

const sections = await Promise.all(
  files.map(async (name) => {
    const source = (await readFile(join(splitDirectory, name), "utf8")).trimEnd();
    return `// ---- ${name} ----\n${source}`;
  }),
);

const generated = [
  "// Generated by build-apps-script.mjs. Edit apps-script-split/*.gs instead.",
  ...sections,
].join("\n\n") + "\n";

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8");
  if (current !== generated) {
    console.error("apps-script/Code.gs is out of date. Run: node build-apps-script.mjs");
    process.exitCode = 1;
  } else {
    console.log(`Code.gs is synchronized from ${files.length} split files.`);
  }
} else {
  await writeFile(outputPath, generated);
  console.log(`Generated Code.gs from ${files.length} split files.`);
}
